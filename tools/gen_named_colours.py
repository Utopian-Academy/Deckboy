"""Builds the two bundled colour tables for Deckboy's named-colour search.

CSS: the named-color table of CSS Color Module Level 4 (w3c/csswg-drafts).
RAL: the RAL Classic sRGB approximations from the MIT-licensed ral_colors_list
gem (github.com/soul933k/ral_colors_list, lib/data/ral_colors.yml). Its licence
travels with the data: native/third_party/ral_colors_list/LICENSE.

RAL colours are physical paints, so any sRGB value is an approximation, and
sources disagree by a few levels; this one is used as published. It has 214 of
the Classic colours (RAL 1000 is not among them).

Usage, with both sources downloaded into a folder of their own:
  curl -sLo css4.bs https://raw.githubusercontent.com/w3c/csswg-drafts/main/css-color-4/Overview.bs
  curl -sLo ral.yml https://raw.githubusercontent.com/soul933k/ral_colors_list/main/lib/data/ral_colors.yml
  python -I tools/gen_named_colours.py css4.bs ral.yml native/core/named_colours_data.inc
"""
import re
import sys

css_path, ral_path, out_path = sys.argv[1:4]

css = []
for line in open(css_path, encoding="utf-8"):
    m = re.search(r"<dfn>([a-z]+)</dfn><td>#([0-9a-fA-F]{6})", line)
    if m:
        css.append((m.group(1), m.group(2).lower()))
assert len(css) == 148, len(css)
assert dict(css)["rebeccapurple"] == "663399"

ral = []
name = number = None
for line in open(ral_path, encoding="utf-8"):
    m = re.match(r"\s*:ral_name:\s*(RAL \d{4})\s*$", line)
    if m:
        number = m.group(1)
        continue
    m = re.match(r"\s*:hex_value:\s*'?([0-9A-Fa-f]{6})'?\s*$", line)
    if m and number:
        hexv = m.group(1).lower()
        ral.append([number, hexv, None])
        continue
    m = re.match(r"\s*:english_name:\s*(.+?)\s*$", line)
    if m and ral and ral[-1][2] is None:
        ral[-1][2] = m.group(1)
assert len(ral) >= 200, len(ral)
for entry in ral:
    assert entry[2], entry

def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

with open(out_path, "w", encoding="utf-8", newline="\n") as out:
    out.write("// GENERATED by gen_named_colours.py -- do not edit by hand.\n")
    out.write("// CSS: CSS Color Module Level 4, the named-color table (%d).\n" % len(css))
    out.write("// RAL: RAL Classic sRGB approximations (%d) from ral_colors_list,\n" % len(ral))
    out.write("// MIT licence, Copyright (c) 2023 soul933k: native/third_party/ral_colors_list/LICENSE.\n\n")
    out.write("inline constexpr NamedColour kCssColours[] = {\n")
    for n, h in css:
        out.write("  {%s, 0x%s},\n" % (cstr(n), h))
    out.write("};\n\n")
    out.write("inline constexpr NamedColour kRalColours[] = {\n")
    for number, h, english in ral:
        out.write("  {%s, 0x%s},\n" % (cstr(number + " " + english), h))
    out.write("};\n")
print("css", len(css), "ral", len(ral))
